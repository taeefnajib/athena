def test_python_classification_contains_key_imports():
    code = pipeline_to_python(_classification_spec())
    assert "import pandas as pd" in code
    assert "RandomForestClassifier" in code
    assert "train_test_split" in code
    assert "SimpleImputer" in code


def test_python_classification_has_header():
    code = pipeline_to_python(_classification_spec())
    assert "# Generated by Athena" in code
    assert "# Pipeline: classification" in code


def test_python_regression_contains_linear_regression():
    code = pipeline_to_python(_regression_spec())
    assert "LinearRegression" in code


def test_python_nodes_in_topo_order():
    spec = _classification_spec()
    code = pipeline_to_python(spec)
    # csv_loader must come before imputer
    assert code.index("CSV Loader") < code.index("Imputer")
    # train_test must come before rf
    assert code.index("Train") < code.index("Random Forest")


def test_json_roundtrip():
    spec = _classification_spec()
    json_str = pipeline_to_json(spec)
    import json
    data = json.loads(json_str)
    assert data["version"] == 1
    assert len(data["nodes"]) == 6
    assert len(data["edges"]) == 6
    assert data["name"] == "classification"


def test_json_pretty_printed():
    json_str = pipeline_to_json(_classification_spec())
    assert "\n" in json_str  # has newlines
    assert "  " in json_str  # indented
