import json
import pytest
from pathlib import Path
from fastapi.testclient import TestClient
from athena.main import app
import athena.core.executor as executor_module


@pytest.fixture(autouse=True)
def reset_executor():
    executor_module._active_run_id = None
    executor_module._cancelled_runs.clear()
    yield
    executor_module._active_run_id = None
    executor_module._cancelled_runs.clear()


client = TestClient(app)

IRIS_CSV = str(Path(__file__).parent / "fixtures" / "data" / "iris.csv")


def _simple_spec(csv_path: str = IRIS_CSV) -> dict:
    return {
        "version": 1,
        "name": "test",
        "nodes": [
            {"id": "n1", "type": "csv_loader", "position": {"x": 0, "y": 0}, "config": {"path": csv_path, "sep": ",", "header": True, "encoding": "utf-8"}},
        ],
        "edges": [],
    }


def _cycle_spec() -> dict:
    return {
        "version": 1,
        "name": "cycle",
        "nodes": [
            {"id": "a", "type": "csv_loader", "position": {"x": 0, "y": 0}, "config": {}},
            {"id": "b", "type": "imputer", "position": {"x": 200, "y": 0}, "config": {}},
        ],
        "edges": [
            {"id": "e1", "source": "a", "target": "b", "source_port": 0, "target_port": 0},
            {"id": "e2", "source": "b", "target": "a", "source_port": 0, "target_port": 0},
        ],
    }


def test_run_returns_run_id():
    resp = client.post("/api/pipelines/run", json={"spec": _simple_spec()})
    assert resp.status_code == 200
    data = resp.json()
    assert "run_id" in data
    assert isinstance(data["run_id"], str)


def test_run_rejects_cycle():
    resp = client.post("/api/pipelines/run", json={"spec": _cycle_spec()})
    assert resp.status_code == 400
    detail = resp.json().get("detail", {})
    assert "PIPELINE_HAS_CYCLE" in str(detail)


def test_run_rejects_concurrent(monkeypatch):
    monkeypatch.setattr(executor_module, "_active_run_id", "existing-run")
    resp = client.post("/api/pipelines/run", json={"spec": _simple_spec()})
    assert resp.status_code == 409


def test_save_and_load(tmp_path: Path):
    path = str(tmp_path / "test.athena")
    spec = _simple_spec()

    save_resp = client.post("/api/pipelines/save", json={"path": path, "spec": spec})
    assert save_resp.status_code == 200
    assert save_resp.json()["ok"] is True

    load_resp = client.post("/api/pipelines/load", json={"path": path})
    assert load_resp.status_code == 200
    loaded = load_resp.json()["spec"]
    assert loaded["name"] == "test"
    assert len(loaded["nodes"]) == 1


def test_load_missing_file():
    resp = client.post("/api/pipelines/load", json={"path": "/does/not/exist.athena"})
    assert resp.status_code == 404


def test_export_python():
    resp = client.post("/api/pipelines/export", json={"spec": _simple_spec(), "format": "python"})
    assert resp.status_code == 200
    assert resp.headers["content-type"].startswith("text/x-python")
    content = resp.content.decode()
    assert "Generated by Athena" in content
    assert "csv_loader" in content.lower() or "CSV" in content


def test_export_json():
    resp = client.post("/api/pipelines/export", json={"spec": _simple_spec(), "format": "json"})
    assert resp.status_code == 200
    data = json.loads(resp.content)
    assert data["version"] == 1


def test_autosave_roundtrip():
    spec = _simple_spec()
    save_resp = client.post("/api/pipelines/autosave", json={"spec": spec})
    assert save_resp.status_code == 200

    load_resp = client.get("/api/pipelines/autosave/latest")
    assert load_resp.status_code == 200
    loaded = load_resp.json()["spec"]
    assert loaded["name"] == "test"


def test_nodes_endpoint():
    resp = client.get("/api/nodes")
    assert resp.status_code == 200
    body = resp.json()
    nodes = {n["type"]: n for n in body["nodes"]}
    assert {"csv_loader", "imputer", "rf"} <= nodes.keys()
    rf = nodes["rf"]
    assert rf["label"] == "Random Forest" and rf["category"] == "model"
    assert [p["name"] for p in rf["outputs"]] == ["model"]
    assert {f["id"] for f in rf["config"]} >= {"n_estimators", "max_depth"}
    assert any(c["id"] == "model" for c in body["categories"])


def test_cancel_run():
    resp = client.post("/api/runs/fake-run-id/cancel")
    assert resp.status_code == 200
    assert resp.json()["ok"] is True
