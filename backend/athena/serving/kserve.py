"""Deploy a model bundle to KServe: an InferenceService running the bundle's image on a Kubernetes cluster.

The image is the bundle's own (Build → Docker image, then Push to a registry the cluster can pull from); the
service answers KServe's V1 protocol (``/v1/models/<name>:predict``) next to ``/predict``. ``manifest`` is the
InferenceService as data: Athena applies it through a saved Kubernetes connection, or you download it as YAML and
``kubectl apply`` it yourself. Where a bundle was deployed is remembered in ``<bundle>/kserve.json``.
"""
from __future__ import annotations

import json
import re
from typing import Any

from athena.schemas.pipeline import Resources
from athena.serving.bundle import bundle_path

GROUP, VERSION, PLURAL = "serving.kserve.io", "v1beta1", "inferenceservices"
PORT = 8000  # the bundle's Dockerfile serves service.py on 8000


class KServeError(Exception):
    """The InferenceService couldn't be applied, read or deleted."""


def isvc_name(slug: str) -> str:
    """A DNS-1123 name short enough for KServe's generated hostnames."""
    name = re.sub(r"[^a-z0-9-]+", "-", slug.lower()).strip("-")[:40].strip("-")
    return name if name and name[0].isalpha() else f"m-{name}"[:40]


def manifest(slug: str, image: str, namespace: str, min_replicas: int = 1, max_replicas: int = 1,
             resources: Resources | None = None, service_account: str = "", image_pull_secret: str = "") -> dict[str, Any]:
    from athena.runtime.k8s_runtime import resources_block
    if not image.strip():
        raise KServeError("Choose the image to deploy: build the bundle's Docker image and push it to a registry the cluster can pull from")
    container: dict[str, Any] = {
        "name": "kserve-container", "image": image,
        "ports": [{"containerPort": PORT, "protocol": "TCP"}],
        "readinessProbe": {"httpGet": {"path": "/health", "port": PORT}, "initialDelaySeconds": 5, "periodSeconds": 5},
    }
    block = resources_block(resources)
    if block:
        container["resources"] = block
    predictor: dict[str, Any] = {"minReplicas": max(0, min_replicas), "maxReplicas": max(max_replicas, min_replicas, 1),
                                 "containers": [container]}
    if service_account:
        predictor["serviceAccountName"] = service_account
    if image_pull_secret:
        predictor["imagePullSecrets"] = [{"name": image_pull_secret}]
    return {"apiVersion": f"{GROUP}/{VERSION}", "kind": "InferenceService",
            "metadata": {"name": isvc_name(slug), "namespace": namespace,
                         "labels": {"app.kubernetes.io/managed-by": "athena", "athena/model": slug[:63]}},
            "spec": {"predictor": predictor}}


def to_yaml(m: dict[str, Any]) -> str:
    import yaml
    return "# Generated by Athena: kubectl apply -f this file (needs KServe on the cluster)\n" + yaml.safe_dump(m, sort_keys=False)


def _api(connection: str) -> tuple[Any, Any]:
    from athena.connectors import kubernetes as kube
    from athena.connectors.store import get_connection, resolve_connection
    if get_connection(connection).get("type") != "kubernetes":
        raise KServeError(f"Connection {connection!r} isn't a Kubernetes cluster connection")
    _, cfg = resolve_connection(connection)
    try:
        return kube.custom_objects(cfg), cfg  # type: ignore[arg-type]
    except ImportError as exc:
        from athena.runtime.adapters import K8S_HINT
        raise KServeError(K8S_HINT) from exc
    except Exception as exc:  # kubeconfig problems come in many types
        raise KServeError(f"Couldn't load the Kubernetes configuration for {connection!r} ({str(exc).splitlines()[0][:160]}): "
                          "check its kubeconfig file and context under Connections") from exc


def _explain(exc: Exception, what: str) -> KServeError:
    status = getattr(exc, "status", None)
    if status == 404 and what.startswith("create"):
        return KServeError("KServe isn't installed on this cluster (no InferenceService resource), or the namespace doesn't exist")
    if status in (401, 403):
        return KServeError(f"The cluster refused to {what}: check the connection's permissions in its namespace")
    return KServeError(f"Couldn't {what}: {str(getattr(exc, 'reason', '') or exc).splitlines()[0][:200]}")


def deploy(slug: str, connection: str, image: str, min_replicas: int = 1, max_replicas: int = 1,
           resources: Resources | None = None) -> dict[str, Any]:
    path = bundle_path(slug)
    api, cfg = _api(connection)
    m = manifest(path.name, image, cfg.namespace, min_replicas, max_replicas, resources, cfg.service_account, cfg.image_pull_secret)
    name, ns = m["metadata"]["name"], cfg.namespace
    try:
        api.create_namespaced_custom_object(GROUP, VERSION, ns, PLURAL, m)
    except Exception as exc:
        if getattr(exc, "status", None) != 409:  # 409: it exists, replace it with this version
            raise _explain(exc, "create the InferenceService") from exc
        try:
            current = api.get_namespaced_custom_object(GROUP, VERSION, ns, PLURAL, name)
            m["metadata"]["resourceVersion"] = current["metadata"]["resourceVersion"]
            api.replace_namespaced_custom_object(GROUP, VERSION, ns, PLURAL, name, m)
        except Exception as exc2:
            raise _explain(exc2, "update the InferenceService") from exc2
    record = {"connection": connection, "namespace": ns, "name": name, "image": image,
              "min_replicas": m["spec"]["predictor"]["minReplicas"], "max_replicas": m["spec"]["predictor"]["maxReplicas"]}
    (path / "kserve.json").write_text(json.dumps(record, indent=2), encoding="utf-8")
    return status(slug)


def deployment(slug: str) -> dict[str, Any] | None:
    saved = bundle_path(slug) / "kserve.json"
    return json.loads(saved.read_text(encoding="utf-8")) if saved.exists() else None


def status(slug: str) -> dict[str, Any]:
    """Where the bundle is deployed and whether it's ready: {"deployed", "ready", "url", "conditions", ...}."""
    rec = deployment(slug)
    if rec is None:
        return {"deployed": False}
    api, _ = _api(rec["connection"])
    try:
        obj = api.get_namespaced_custom_object(GROUP, VERSION, rec["namespace"], PLURAL, rec["name"])
    except Exception as exc:
        if getattr(exc, "status", None) == 404:
            return {**rec, "deployed": False, "ready": False, "url": "", "conditions": [],
                    "message": "The InferenceService no longer exists on the cluster"}
        raise _explain(exc, "read the InferenceService") from exc
    st = obj.get("status") or {}
    conditions = [{"type": c.get("type", ""), "status": c.get("status", ""), "reason": c.get("reason", ""),
                   "message": c.get("message", "")} for c in st.get("conditions", [])]
    ready = any(c["type"] == "Ready" and c["status"] == "True" for c in conditions)
    url = st.get("url", "")
    problem = next((c["message"] or c["reason"] for c in conditions if c["status"] == "False" and (c["message"] or c["reason"])), "")
    return {**rec, "deployed": True, "ready": ready, "url": url, "conditions": conditions,
            "predict_url": f"{url}/v1/models/{rec['name']}:predict" if url else "", "message": "" if ready else problem}


def undeploy(slug: str) -> None:
    rec = deployment(slug)
    if rec is None:
        return
    api, _ = _api(rec["connection"])
    try:
        api.delete_namespaced_custom_object(GROUP, VERSION, rec["namespace"], PLURAL, rec["name"])
    except Exception as exc:
        if getattr(exc, "status", None) != 404:
            raise _explain(exc, "delete the InferenceService") from exc
    (bundle_path(slug) / "kserve.json").unlink(missing_ok=True)
