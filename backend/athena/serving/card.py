"""Evidence for a deployed model, gathered from the run, and the model card written into its bundle.

Evaluation = the reports of nodes that consumed the model in that run (Metrics, Fairness Check, ...). Quality gates =
Quality Gate nodes that checked it (or the deployed node itself, when you deploy a gate's output). A gate without a
saved result failed (with on_fail=stop) or didn't run; the card says so rather than claiming a pass.
"""
from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from athena.core.artifacts import ArtifactNotFound, load_output
from athena.core.registry import NODE_META
from athena.schemas.pipeline import PipelineSpec


def _model_consumers(spec: PipelineSpec, model_id: str) -> list[str]:
    out = []
    for e in spec.edges:
        if e.source != model_id:
            continue
        meta = NODE_META.get(spec.node(e.target).type)
        if meta and e.target_port < len(meta.inputs) and meta.inputs[e.target_port].type == "model" and e.target not in out:
            out.append(e.target)
    return out


def gather_evidence(spec: PipelineSpec, run_id: str, node_id: str) -> dict[str, Any]:
    models = [node_id]
    if spec.node(node_id).type == "quality_gate":  # deploying a gate's output: the model behind it counts too
        src = next((e.source for e in spec.edges if e.target == node_id and e.target_port == 3), None)
        if src:
            models.append(src)
    consumers = [c for m in models for c in _model_consumers(spec, m)]
    if spec.node(node_id).type == "quality_gate":
        consumers.insert(0, node_id)
    evaluation: list[dict[str, Any]] = []
    gates: list[dict[str, Any]] = []
    for cid in dict.fromkeys(consumers):
        node = spec.node(cid)
        meta = NODE_META.get(node.type)
        if meta is None:
            continue
        if node.type == "quality_gate":
            try:
                report = load_output(run_id, cid, 1)
                passed: bool | None = bool(report.get("passed"))
            except ArtifactNotFound:
                passed = None
            gates.append({"node": meta.label, "id": cid, "rules": str(node.config.get("rules", "")).strip(),
                          "on_fail": node.config.get("on_fail", "stop"), "passed": passed})
            continue
        report_ports = [i for i, p in enumerate(meta.outputs) if p.type == "report"]
        if not report_ports:
            continue
        try:
            report = load_output(run_id, cid, report_ports[0])
        except ArtifactNotFound:
            continue
        if isinstance(report, dict):
            numbers = {str(k): float(v) for k, v in report.items() if isinstance(v, (int, float)) and not isinstance(v, bool)}
            evaluation.append({"node": meta.label, "id": cid, "report": numbers})
    return {"evaluation": evaluation, "quality_gates": gates}


def _fmt(v: float) -> str:
    return f"{v:.4g}"


def model_card(schema: dict[str, Any], rows: int) -> str:
    """MODEL_CARD.md: what the model is, what it was trained and checked on, and what to watch out for."""
    src = schema.get("source", {})
    lines = [f"# Model card: {schema['name']}", "",
             f"Generated by Athena on {datetime.now(UTC).strftime('%Y-%m-%d')} from node **{src.get('node_label')}** of pipeline "
             f"**{src.get('pipeline')}** (run `{src.get('run_id')}`). Fill in the sections marked _to complete_.", "",
             "## Model", "", f"- Type: `{schema['model']}` ({schema['task']})", f"- Version: {schema['version']}"]
    if schema.get("classes"):
        lines.append(f"- Classes: {', '.join(map(str, schema['classes']))}")
    lines += ["", "## Intended use", "", "_to complete: who uses the predictions, for what decisions, and what is out of scope._", "",
              "## Data", "", f"- Trained on {rows:,} rows and {len(schema.get('model_features', []))} model features.",
              f"- Requests take {len(schema['features'])} input column(s): {', '.join(f['name'] for f in schema['features'])}."]
    if schema.get("preprocessing_replayed"):
        lines.append(f"- Preprocessing applied by the service: {' → '.join(schema['preprocessing_replayed'])}"
                     + (" (verified to reproduce training exactly)." if schema.get("preprocessing_verified") else "."))
    if schema.get("preprocessing_not_included"):
        lines.append(f"- **Not applied by the service** (requests must already reflect them): {', '.join(schema['preprocessing_not_included'])}.")
    lines += ["", "## Evaluation", ""]
    if schema.get("evaluation"):
        for ev in schema["evaluation"]:
            lines += [f"**{ev['node']}** (`{ev['id']}`)", "", "| Metric | Value |", "|---|---|"]
            lines += [f"| {k} | {_fmt(v)} |" for k, v in ev["report"].items()]
            lines.append("")
    else:
        lines += ["No evaluation node consumed this model in the run (add Metrics or Fairness Check).", ""]
    lines += ["## Quality gates", ""]
    if schema.get("quality_gates"):
        for g in schema["quality_gates"]:
            state = {True: "passed", False: "failed (warn only)", None: "**did not pass in this run** (it failed and stopped the run, or didn't run)"}[g["passed"]]
            lines += [f"- **{g['node']}** (`{g['id']}`): {state}", "", "  ```", *[f"  {r}" for r in g["rules"].splitlines() if r.strip()], "  ```"]
    else:
        lines.append("No Quality Gate checked this model.")
    lines += ["", "## Limitations and risks", "", "_to complete: known failure modes, groups it may serve worse, data it shouldn't see._"]
    if schema.get("needs_athena"):
        lines.append("- Uses an Athena estimator class: install `athena-backend` where it runs.")
    lines += ["- Metrics come from the pipeline's held-out split; monitor live performance and drift after deployment.", ""]
    return "\n".join(lines)
