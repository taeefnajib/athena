"""One task per node: turn a pipeline into a module of step functions an orchestrator can run separately.

``pipeline_to_steps(spec)`` writes ``<module>_steps.py``: the same imports and helpers as the exported script, then
one function per node holding exactly that node's exported code. A step loads its inputs from the run's artifact
folder and saves its outputs there (pickle files), so each node can be its own Airflow task or Dagster op and a
failed node can be retried alone. ``run_step(node_id, run_id)`` is what a task calls; it returns False when a
Quality Gate skipped (``SystemExit(0)``), so the orchestrator skips what comes after it.

Running the module directly (``python <module>_steps.py``) runs every step in order, like the script.
"""
from __future__ import annotations

import textwrap

from athena.core.codegen import _header, build_sections, output_vars, safe
from athena.core.dag import topo_sort
from athena.schemas.pipeline import PipelineSpec

_RUNTIME = '''

# --- Running steps -------------------------------------------------------------------------------------------
# Each step reads its inputs from, and writes its outputs to, the run's artifact folder:
#   $ATHENA_ARTIFACTS/<pipeline>/<run id>/   (default: the system temp folder)
# With several machines (Celery, Kubernetes executors), point ATHENA_ARTIFACTS at storage they all share.
ARTIFACTS = Path(os.environ.get("ATHENA_ARTIFACTS", Path(tempfile.gettempdir()) / "athena_artifacts")) / {module!r}


class Artifacts:
    """The outputs of one run, one pickle file per variable."""

    def __init__(self, run_id: str) -> None:
        self.folder = ARTIFACTS / re.sub(r"[^\\w.-]", "_", str(run_id))
        self.folder.mkdir(parents=True, exist_ok=True)

    def load(self, name: str):
        path = self.folder / f"{{name}}.pkl"
        if not path.exists():
            raise RuntimeError(f"{{name}} hasn't been produced in this run (did the step that makes it run?)")
        with path.open("rb") as fh:
            return pickle.load(fh)

    def save(self, name: str, value) -> None:
        with (self.folder / f"{{name}}.pkl").open("wb") as fh:
            pickle.dump(value, fh)


def run_step(node_id: str, run_id: str) -> bool:
    """Run one node. True when it finished; False when a Quality Gate skipped the rest of the pipeline.
    Any error, including a failing gate, raises."""
    try:
        STEPS[node_id](Artifacts(run_id))
    except SystemExit as exc:
        if exc.code in (0, None):
            return False
        raise RuntimeError(str(exc.code)) from None
    return True


if __name__ == "__main__":  # run every step in order, like the exported script
    import uuid

    _run = f"local-{{uuid.uuid4().hex[:8]}}"
    for _node in ORDER:
        if not run_step(_node, _run):
            print(f"{{_node}}: skipped the rest of the pipeline")
            break
'''


def step_plan(spec: PipelineSpec) -> tuple[list[str], list[tuple[str, str]], dict[str, str]]:
    """(node ids in run order, node-level dependencies, node id -> label) after expanding subflows."""
    from athena.core.subflows import expand
    flat, _ = expand(spec)
    order = topo_sort([{"id": n.id} for n in flat.nodes], [{"source": e.source, "target": e.target} for e in flat.edges])
    deps = sorted({(e.source, e.target) for e in flat.edges})
    return order, deps, {s.node_id: s.label for s in build_sections(spec)}


def pipeline_to_steps(spec: PipelineSpec, module: str) -> str:
    from athena.core.subflows import expand
    flat, _ = expand(spec)
    sections = build_sections(spec)
    imports, helpers = _header(sections)
    out = ["# Generated by Athena: one function per node, for orchestrators (see run_step at the bottom)",
           f"# Pipeline: {spec.name}", "", "from __future__ import annotations", "", "import os", "import pickle", "import re", "import tempfile", "from pathlib import Path"]
    out += [i for i in imports if i not in out]
    if helpers:
        out += ["", ""] + ["\n\n\n".join(h.rstrip() for h in helpers)]
    names: dict[str, str] = {}
    for s in sections:
        node = next((n for n in flat.nodes if n.id == s.node_id), None)
        fn = f"step_{safe(s.node_id)}"
        names[s.node_id] = fn
        loads, saves = [], []
        if node is not None:
            for e in sorted((e for e in flat.edges if e.target == node.id), key=lambda e: e.target_port):
                src = output_vars(e.source, flat.node(e.source).type)
                if e.source_port < len(src):
                    var = src[e.source_port]
                    line = f"    {var} = art.load({var!r})"
                    if line not in loads:
                        loads.append(line)
            saves = [f"    art.save({v!r}, {v})" for v in output_vars(node.id, node.type)]
        body = textwrap.indent(s.code, "    ") if s.exported else textwrap.indent(s.code, "    ") + "\n    raise NotImplementedError('This node can\\'t be exported')"
        out += ["", "", f"def {fn}(art: Artifacts) -> None:", f'    """{s.label} ({s.node_id})"""', *loads, body,
                *(saves if s.exported else [])]
    out.append("")
    out.append("")
    out.append("STEPS = {" + ", ".join(f"{nid!r}: {fn}" for nid, fn in names.items()) + "}")
    out.append("ORDER = " + repr(list(names)))
    # Artifacts / run_step are referenced by the steps above only at call time, so defining them last is fine
    return "\n".join(out) + _RUNTIME.format(module=module)
