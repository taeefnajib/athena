"""Export a pipeline to an orchestrator: an Airflow DAG or a Dagster job running it on a cron schedule.

The pipeline runs as **one task per node**, wired like the graph, so the orchestrator shows each step and can retry
one alone. The zip holds:

- ``<name>_steps.py``: one function per node with exactly the code Export Code writes for it
  (``core/orchestrator_steps.py``); steps pass data through pickle files in a per-run folder;
- ``<name>_airflow.py`` / ``<name>_dagster.py``: the tasks and their dependencies;
- ``<name>_pipeline.py``: the whole pipeline as one script (Export Code > Python), to check it runs on that machine;
- a README.

A Quality Gate with ``on_fail=skip`` that isn't met skips the nodes after it (Airflow: skipped tasks; Dagster:
skipped ops); a failing gate fails its task, and what depends on it doesn't run.
"""
from __future__ import annotations

import io
import re
import zipfile

from athena.core.codegen import pipeline_to_python, safe
from athena.core.cron import parse
from athena.core.orchestrator_steps import pipeline_to_steps, step_plan
from athena.schemas.pipeline import PipelineSpec

TARGETS = ("airflow", "dagster")

AIRFLOW = '''"""Airflow DAG for the Athena pipeline "{name}", generated by Athena.

Copy this file and {module}_steps.py into your DAGs folder. Each node of the pipeline is a task, scheduled on
"{cron}" ({tz_note}). The workers need the packages the pipeline imports, and a folder all tasks of a run can reach
(ATHENA_ARTIFACTS; the system temp folder by default, fine for one machine).
"""
import sys
from datetime import datetime
from pathlib import Path

from airflow import DAG
from airflow.exceptions import AirflowSkipException

try:  # Airflow 3
    from airflow.providers.standard.operators.python import PythonOperator
except ImportError:  # Airflow 2
    from airflow.operators.python import PythonOperator

sys.path.insert(0, str(Path(__file__).parent))  # {module}_steps.py lives next to this file

NODES = {nodes!r}  # node id -> task id, in run order
DEPENDENCIES = {deps!r}  # (upstream node, downstream node), from the pipeline's connections


def run_node(node_id: str, **context) -> None:
    from {module}_steps import run_step  # imported when the task runs, not when Airflow parses the DAG

    if not run_step(node_id, context["run_id"]):
        raise AirflowSkipException("A Quality Gate's rules weren't met: the tasks after it are skipped")


with DAG(
    dag_id="athena_{module}",
    description={name!r},
    schedule={cron!r},
    start_date=datetime(2026, 1, 1),
    catchup=False,  # like Athena: runs missed while the scheduler was down aren't caught up
    max_active_runs=1,  # and they never overlap
    tags=["athena"],
) as dag:
    tasks = {{node: PythonOperator(task_id=task, python_callable=run_node, op_kwargs={{"node_id": node}})
             for node, task in NODES.items()}}
    for upstream, downstream in DEPENDENCIES:
        tasks[upstream] >> tasks[downstream]
'''

DAGSTER = '''"""Dagster job for the Athena pipeline "{name}", generated by Athena.

    pip install dagster dagster-webserver && dagster dev -f {module}_dagster.py

Keep {module}_steps.py next to this file. Each node of the pipeline is an op, scheduled on "{cron}" ({tz_note}).
Ops of a run share a folder (ATHENA_ARTIFACTS; the system temp folder by default, fine for one machine).
"""
import sys
from pathlib import Path

from dagster import DefaultScheduleStatus, Definitions, In, Nothing, Out, Output, ScheduleDefinition, job, op

sys.path.insert(0, str(Path(__file__).parent))  # {module}_steps.py lives next to this file

NODES = {nodes!r}  # node id -> op name, in run order
DEPENDENCIES = {deps!r}  # (upstream node, downstream node), from the pipeline's connections


def node_op(node_id: str, name: str):
    upstream = [NODES[a] for a, b in DEPENDENCIES if b == node_id]

    @op(name=name, ins={{f"after_{{u}}": In(Nothing) for u in upstream}}, out=Out(Nothing, is_required=False))
    def _run(context):
        from {module}_steps import run_step

        if run_step(node_id, context.run_id):
            yield Output(None)
        else:  # no output: the ops after this one are skipped
            context.log.info("A Quality Gate's rules weren't met: the ops after it are skipped")

    return _run


OPS = {{node: node_op(node, name) for node, name in NODES.items()}}


@job(name="athena_{module}", description={name!r})
def athena_pipeline() -> None:
    done = {{}}
    for node in NODES:
        done[node] = OPS[node](**{{f"after_{{NODES[a]}}": done[a] for a, b in DEPENDENCIES if b == node}})


schedule = ScheduleDefinition(job=athena_pipeline, cron_schedule={cron!r}, default_status=DefaultScheduleStatus.RUNNING)
defs = Definitions(jobs=[athena_pipeline], schedules=[schedule])
'''

README = '''# {name}: {target} export

Generated by Athena.

- `{orchestrator}`: {how}
- `{module}_steps.py`: one function per node, with the code Export Code writes for it. Each node runs as its own
  task and passes its outputs to the next ones through pickle files in `$ATHENA_ARTIFACTS/{module}/<run id>/`
  (the system temp folder by default). On several machines, point `ATHENA_ARTIFACTS` at a folder they all share.
  `python {module}_steps.py` runs every step in order.
- `{module}_pipeline.py`: the whole pipeline as one standalone script (Export Code > Python), to check it works on
  the machine that will run it: `python {module}_pipeline.py`.

Schedule: `{cron}` ({description}). {tz_note_cap}.

Paths in the pipeline (data files, model files) are the ones it used in Athena: make sure they exist where the
tasks run. Connections are read from environment variables (see the comments in the steps); credentials are never
written into these files. A Quality Gate set to skip that isn't met skips the tasks after it; a failing gate fails.
'''


def module_name(name: str) -> str:
    s = re.sub(r"\W+", "_", name.strip().lower()).strip("_") or "pipeline"
    return s if not s[0].isdigit() else f"p_{s}"


def orchestrator_zip(spec: PipelineSpec, target: str, cron: str) -> tuple[bytes, str]:
    """(zip bytes, file name) for an Airflow or Dagster export of ``spec`` scheduled on ``cron``."""
    from athena.core.cron import describe
    if target not in TARGETS:
        raise ValueError(f"Unknown orchestrator {target!r} ({', '.join(TARGETS)})")
    description = describe(parse(cron))  # validates the expression
    name = spec.name or "pipeline"
    module = module_name(name)
    tz_note = ("in the DAG's timezone: UTC unless your Airflow sets default_timezone" if target == "airflow"
               else "in UTC unless you add execution_timezone to the ScheduleDefinition")
    order, deps, _labels = step_plan(spec)
    nodes = {nid: f"step_{safe(nid)}" for nid in order}
    fmt = {"name": name, "module": module, "cron": cron, "tz_note": tz_note, "nodes": nodes, "deps": deps}
    orchestrator = f"{module}_{target}.py"
    source = (AIRFLOW if target == "airflow" else DAGSTER).format(**fmt)
    steps = pipeline_to_steps(spec, module)
    compile(source, orchestrator, "exec")  # never hand out a file that doesn't parse
    compile(steps, f"{module}_steps.py", "exec")
    how = ("copy it and the steps module into your Airflow DAGs folder; the DAG appears as "
           f"`athena_{module}`." if target == "airflow" else
           f"`pip install dagster dagster-webserver`, then `dagster dev -f {orchestrator}` (the schedule starts on).")
    readme = README.format(**fmt, target=target.capitalize(), orchestrator=orchestrator, how=how, description=description,
                           tz_note_cap=tz_note[0].upper() + tz_note[1:])
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{module}/{module}_steps.py", steps)
        z.writestr(f"{module}/{module}_pipeline.py", pipeline_to_python(spec))
        z.writestr(f"{module}/{orchestrator}", source)
        z.writestr(f"{module}/README.md", readme)
    return buf.getvalue(), f"{module}_{target}.zip"
